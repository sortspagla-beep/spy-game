export function getAvatarById(id?: string): AvatarItem | undefined {
  if (!id) return undefined;
  return AVATAR_LIST.find((a) => a.id === id);
}

// Fallback deterministic palette for users who haven't selected an avatar yet
const FALLBACK_COLORS = [
  'bg-rose-500 text-white',
  'bg-amber-400 text-slate-900',
  'bg-cyan-400 text-slate-900',
  'bg-violet-500 text-white',
  'bg-emerald-400 text-slate-900',
  'bg-fuchsia-500 text-white',
];

export function getFallbackAvatarColor(username: string): string {
  const code = username.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
  return FALLBACK_COLORS[code % FALLBACK_COLORS.length];
}
